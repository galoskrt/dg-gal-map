# map_delivery ו-remind_10m פטורים מחלון השליחה (תגובה מיידית ותזכורת
# עשר הדקות). watched_no_booking כבוי. הסדר משקף את מהלך המשפך.
ORDER = ["map_delivery", "watched_no_booking", "bounced_fast", "calendar_no_pick",
         "map_reopened", "book_invite", "booked_confirm", "remind_48h",
         "remind_24h", "remind_2h", "remind_10m", "community"]

DISABLED = {"watched_no_booking"}

# חלון השליחה, שעון ישראל: ראשון עד חמישי 07:00-22:00. מסירת המפה
# ותזכורת עשר הדקות פטורות.
SEND_WINDOW = (7, 22)

if __name__ == "__main__":
    import io
    import re
    import sys

    out, bad, note, checked = [], [], [], 0
    for i, k in enumerate(ORDER):
        m = MESSAGES[k]
        out.append("=" * 66)
        flag = "  [כבוי]" if k in DISABLED else ""
        out.append("%d. %s%s" % (i, m["when"], flag))
        out.append("   למי: %s" % m["who"])
        if m.get("media"):
            out.append("   מצורף: %s" % m["media"])
        out.append("")
        # remind_2h הוא לא נוסח אחד, זו הוכחה שנבחרת לפי מסלול.
        if "proof_a" in m:
            variants = {" · מסלול א (יוסי)": m["text"].replace("{proof}", m["proof_a"]),
                        " · מסלול ב/ג (שירן)": m["text"].replace("{proof}", m["proof_bc"])}
        else:
            variants = {"": m["text"]}
        for label, t in variants.items():
            checked += 1
            out.append(t)
            out.append("")
            if re.search(u"[–—]", t):
                bad.append("%s%s has a dash" % (k, label))
            for g in (u"אתה", u"אתם", u"שלכם", u"תגיד", u"תכתוב", u"תבדוק", u"תאשר"):
                if re.search(u"(?<![֐-׿])" + g + u"(?![֐-׿])", t):
                    bad.append("%s%s uses %s" % (k, label, g))
            if len(t) > 700:
                bad.append("%s%s is %d characters, long for WhatsApp" % (k, label, len(t)))
            emo = re.findall(u"[\U0001F300-\U0001FAFF☀-➿]", t)
            if emo:
                note.append("%s%s: %s" % (k, label, "".join(emo)))

    out.append("=" * 66)
    out.append("")
    out.append("חלון שליחה: %02d:00 עד %02d:00" % SEND_WINDOW)
    out.append("בדיקה: %s" % ("; ".join(bad) if bad
                              else "כל %d הנוסחים עומדים בכללים" % checked))
    if note:
        out.append("אמוג'ים, מכוונים: %s" % "; ".join(note))
    body = "\n".join(out)
    io.open("wa_messages.txt", "w", encoding="utf-8").write(body)
    # קונסול Windows הוא cp1255 ומפיל print על אמוג'ים. הקובץ הוא הפלט
    # האמיתי, וההדפסה רק נוחות, אז מכריחים utf-8 ולא נכשלים אם אי אפשר.
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    try:
        print(body)
    except Exception:
        print("wa_messages.txt written (%d checks)" % checked)
