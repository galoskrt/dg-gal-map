# מציין מקום נקרא כקוד במנוע, אבל במסמך שגל קורא הוא צריך להיקרא כעברית
READABLE = {
    u"{name}": u"‹השם הפרטי›",
    u"{link}": u"‹קישור ליומן›",
    u"{map}": u"‹קישור המפה שלו›",
    u"{zoom}": u"‹קישור הזום של אותה פגישה›",
    u"{when}": u"‹יום ושעה›",
}


def readable(t):
    for k, v in READABLE.items():
        t = t.replace(k, v)
    return t


